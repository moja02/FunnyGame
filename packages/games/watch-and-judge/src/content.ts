let lastWatchAndJudgeTauntIdx = -1;

export function getTaunt(score: number, stage: number): string {
  let pool = watchAndJudgeContent.tauntsLow;
  if (stage >= 17 || score >= 5000) {
    pool = watchAndJudgeContent.tauntsHigh;
  } else if (stage >= 6 || score >= 1500) {
    pool = watchAndJudgeContent.tauntsMid;
  }

  let idx = Math.floor(Math.random() * pool.length);
  if (pool.length > 1 && idx === lastWatchAndJudgeTauntIdx) {
    idx = (idx + 1) % pool.length;
  }
  lastWatchAndJudgeTauntIdx = idx;

  const template = pool[idx]!;
  return template.replace('{score}', score.toLocaleString('en-US'));
}
